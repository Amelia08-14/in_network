function flatten(groups: TaxonomyGroup[]) {
  return groups.flatMap(({ group, labels }) => labels.map((label) => ({ label, group })));
}

export const SKILL_TAGS = flatten(SKILL_GROUPS);
export const SECTOR_TAGS = flatten(SECTOR_GROUPS);

// Contrôle d'unicité (Tag.label est unique, toutes catégories confondues).
{
  const seen = new Map<string, string>();
  for (const { label, group } of [...SKILL_TAGS, ...SECTOR_TAGS]) {
    const key = label.trim().toLowerCase();
    if (seen.has(key)) throw new Error(`Taxonomie : libellé en double « ${label} » (${seen.get(key)} / ${group})`);
    seen.set(key, group);
  }
}

/** Crée ou met à jour (famille) chaque étiquette — ne supprime jamais rien. */
export async function syncTaxonomy(prisma: Prisma.TransactionClient | { tag: Prisma.TransactionClient['tag'] }) {
  for (const { label, group } of SKILL_TAGS) {
    await prisma.tag.upsert({ where: { label }, update: { group, category: 'SKILL' }, create: { label, group, category: 'SKILL' } });
  }
  for (const { label, group } of SECTOR_TAGS) {
    await prisma.tag.upsert({ where: { label }, update: { group, category: 'SECTOR' }, create: { label, group, category: 'SECTOR' } });
  }
  return { skills: SKILL_TAGS.length, sectors: SECTOR_TAGS.length };
}
